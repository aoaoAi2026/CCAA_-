def exam(key, year, month, singles, multis, judges, essays):
    o = f"// {year}年{month}月\n"
    o += f"// {'=' * 60}\n"
    o += f"pastExamsData['{key}'] = {{\n"
    o += f"  year: {year}, month: {month}, questions: 62, duration: 120, passingScore: 70,\n"
    o += "  sections: [\n"
    o += "    { name: '一、单项选择题（每题1分，共30分）', questions: [\n"
    for i, x in enumerate(singles):
        id_, q, opts, ans, a = x
        comma = "," if i < len(singles) - 1 else ""
        o += f"      S({id_}, '{q}', {opts}, '{ans}', '{a}'){comma}\n"
    o += "    ]},\n"
    o += "    { name: '二、多项选择题（每题2分，共20分）', questions: [\n"
    for i, x in enumerate(multis):
        id_, q, opts, ans, a = x
        comma = "," if i < len(multis) - 1 else ""
        o += f"      M({id_}, '{q}', {opts}, {ans}, '{a}'){comma}\n"
    o += "    ]},\n"
    o += "    { name: '三、判断题（每题1分，共10分）', questions: [\n"
    for i, x in enumerate(judges):
        id_, q, ans, a = x
        comma = "," if i < len(judges) - 1 else ""
        o += f"      J({id_}, '{q}', {'true' if ans else 'false'}, '{a}'){comma}\n"
    o += "    ]},\n"
    o += "    { name: '四、简答题（每题10分，共20分）', questions: [\n"
    for i, x in enumerate(essays):
        id_, q, a = x
        comma = "," if i < len(essays) - 1 else ""
        o += f"      E({id_}, '{q}', '{a}'){comma}\n"
    o += "    ]}\n"
    o += "  ]\n};\n\n"
    return o

